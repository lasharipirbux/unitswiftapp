export function convertAnyUnit(value: number, fromUnitId: string, toUnitId: string): number {
  if (fromUnitId === toUnitId) return value;

  const fromUnit = UNITS[fromUnitId];
  const toUnit = UNITS[toUnitId];
  if (!fromUnit || !toUnit) return value;

  if (fromUnit.category === 'temperature' && toUnit.category === 'temperature') {
    // Convert fromUnit to Celsius first
    let celsius = value;
    if (fromUnitId === 'fahrenheit') {
      celsius = (value - 32) / 1.8;
    } else if (fromUnitId === 'kelvin') {
      celsius = value - 273.15;
    }

    // Convert Celsius to toUnit
    if (toUnitId === 'celsius') return celsius;
    if (toUnitId === 'fahrenheit') return celsius * 1.8 + 32;
    if (toUnitId === 'kelvin') return celsius + 273.15;
  }

  const fromFactor = TO_BASE_FACTORS[fromUnitId];
  const toFactor = TO_BASE_FACTORS[toUnitId];
  if (fromFactor !== undefined && toFactor !== undefined) {
    return (value * fromFactor) / toFactor;
  }

  return value;
}

export function formatConvertedNumber(num: number): string {
  if (!Number.isFinite(num)) return '0';
  if (Math.abs(num) < 1e-12) return '0';

  const abs = Math.abs(num);
  if (abs >= 1e12 || abs < 1e-6) {
    return num.toPrecision(6).replace(/\.?0+e/, 'e');
  }

  if (abs < 0.0001) {
    return Number(num.toPrecision(6)).toString();
  }

  // Round up to 4 decimal places while stripping trailing zeros and preventing -0
  const rounded = Number(num.toFixed(4));
  if (rounded === 0) return '0';
  return rounded.toLocaleString('en-US', {
    maximumFractionDigits: 4,
  });
}

export function findConverterByUnits(fromUnitId: string, toUnitId: string): ConverterPageConfig | undefined {
  return CONVERTERS.find(
    (c) => c.fromUnitId === fromUnitId && c.toUnitId === toUnitId
  );
}

export function findConverterBySlug(slug: string): ConverterPageConfig | undefined {
  return CONVERTERS.find((c) => c.slug === slug);
}

